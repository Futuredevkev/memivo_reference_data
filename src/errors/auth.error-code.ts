/**
 * Códigos de error del módulo de autenticación
 */
export enum AuthErrorCode {
  // Login & Credentials
  AUTH_INVALID_CREDENTIALS = 'AUTH_INVALID_CREDENTIALS',
  AUTH_NOT_VERIFIED = 'AUTH_NOT_VERIFIED',
  AUTH_ALREADY_VERIFIED = 'AUTH_ALREADY_VERIFIED',
  LOGIN_FAILED = 'LOGIN_FAILED',
  LOGOUT_FAILED = 'LOGOUT_FAILED',

  // Registration
  AUTH_EMAIL_TAKEN = 'AUTH_EMAIL_TAKEN',
  AUTH_USER_UNDERAGE = 'AUTH_USER_UNDERAGE',
  USER_REGISTRATION_FAILED = 'USER_REGISTRATION_FAILED',
  AUTH_EMAIL_VALIDATION_FAILED = 'AUTH_EMAIL_VALIDATION_FAILED',
  AUTH_CODE_RESEND_FAILED = 'AUTH_CODE_RESEND_FAILED',

  // Verification Codes
  AUTH_CODE_EXPIRED = 'AUTH_CODE_EXPIRED',
  AUTH_CODE_INVALID = 'AUTH_CODE_INVALID',

  // Two-Factor Authentication
  AUTH_2FA_NOT_ENABLED = 'AUTH_2FA_NOT_ENABLED',
  AUTH_2FA_ALREADY_ENABLED = 'AUTH_2FA_ALREADY_ENABLED',
  AUTH_2FA_SETUP_EXPIRED = 'AUTH_2FA_SETUP_EXPIRED',

  // Tokens & Sessions
  AUTH_TOKEN_INVALID = 'AUTH_TOKEN_INVALID',
  AUTH_TOKEN_MALFORMED = 'AUTH_TOKEN_MALFORMED',
  AUTH_ACCESS_DENIED = 'AUTH_ACCESS_DENIED',
  AUTH_SESSION_NOT_FOUND = 'AUTH_SESSION_NOT_FOUND',

  // ── LA OPERACIÓN QUE PIDIÓ LA PERSONA FALLÓ POR ALGO INESPERADO ──────────
  // Status 500 y sufijo `_FAILED`. Cada código nombra la operación del BORDE
  // —lo que la persona pidió—, no un paso de adentro. Antes caían en
  // `INTERNAL_SERVER_ERROR` y la app decía «Error interno del servidor» en vez
  // de qué fue lo que no se pudo hacer.
  AUTH_PASSWORD_RESET_FAILED = 'AUTH_PASSWORD_RESET_FAILED',
}
